// glues report_body.html + an appendix with all my code/config/evidence into project_report.html, then makes the PDF
//   node docs/build_report.js
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const file = (f, label) => `<div class="fn">${label || f}</div><pre>${esc(fs.readFileSync(path.join(root, f), 'utf8').trim())}</pre>`;

const code = [
  ['simulator/room.js'], ['simulator/house.js'], ['lambdas/log-reading/index.mjs'], ['lambdas/control-light/index.mjs'],
  ['nodered/buildflow.js', 'nodered/buildflow.js (generates the Node-RED flows.json)'], ['loadtest/loadtest.js'], ['loadtest/cloudwatch-graphs.js'],
  ['simulator/security-test.js'], ['dashboard/server.js'], ['config.js'],
];
const config = [
  ['infra/setup.sh'], ['infra/add-device.sh'], ['infra/update-lambdas.sh'], ['infra/teardown.sh'], ['loadtest/provision-load-rooms.sh'],
  ['infra/policies/device-policy.json'], ['infra/policies/gateway-policy.json'], ['infra/policies/log-role-policy.json'],
  ['infra/policies/control-role-policy.json'], ['infra/policies/lambda-trust.json'], ['infra/policies/rule.json'], ['package.json'],
];

const body = fs.readFileSync(__dirname + '/report_body.html', 'utf8');
const appendix = `
<div class="appx">
<h2 class="pb">Appendix A – Evidence Files</h2>
${fs.readFileSync(__dirname + '/appendix_evidence.html', 'utf8')}
<h2 class="pb">Appendix B – Code</h2>
<p>Everything is in my local git repo <code>sit314_distinction</code> (GitHub link: <i>to be added</i>). The Node-RED <code>flows.json</code> is generated by <code>buildflow.js</code>, so I've put that script here instead of the 300-line JSON.</p>
${code.map(([f, l]) => file(f, l)).join('\n')}
<h2 class="pb">Appendix C – Configuration (AWS scripts, policies, IoT rule)</h2>
<p>REGION / ACCOUNT get filled in by <code>setup.sh</code> when it runs.</p>
${config.map(([f, l]) => file(f, l)).join('\n')}
<h2 class="pb">Appendix D – Raw Output</h2>
${file('evidence/loadtest_console_trimmed.log', 'evidence/loadtest_console.log (load test terminal output, trimmed - the full file has every light switch)')}
${file('evidence/security_test.log', 'evidence/security_test.log')}
${file('evidence/setup.log', 'evidence/setup.log (running infra/setup.sh on a fresh account)')}
</div>`;

const html = body.replace('<!--APPENDIX-->', appendix);
fs.writeFileSync(__dirname + '/project_report.html', html);
const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
execFileSync(chrome, ['--headless=new', '--disable-gpu', '--no-pdf-header-footer', `--print-to-pdf=${__dirname}/project_report.pdf`, `file://${__dirname}/project_report.html`], { stdio: 'ignore' });
console.log('built docs/project_report.pdf');
